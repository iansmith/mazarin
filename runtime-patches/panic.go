// bugbPuts writes a string directly to UART via kmazarinUART, bypassing
// suppressSerial. Used by throwPreDiag to ensure diagnostic output is visible.
//
//go:nosplit
func bugbPuts(s string) {
	for i := 0; i < len(s); i++ {
		kmazarinUART(s[i])
	}
}

// bugbPutHex64 writes a uint64 as 16 hex digits directly to UART.
//
//go:nosplit
func bugbPutHex64(v uint64) {
	for i := 60; i >= 0; i -= 4 {
		nibble := byte((v >> uint(i)) & 0xF)
		if nibble < 10 {
			kmazarinUART('0' + nibble)
		} else {
			kmazarinUART('a' - 10 + nibble)
		}
	}
}

// bugbDumpContext dumps 32 bytes of context starting at addr.
// maxAddr is the upper bound for safe reads — bytes at or beyond maxAddr
// are displayed as ??/* rather than read. Used to identify the full source
// string containing " failed " (0x2064656C69616620).
//
//go:nosplit
func bugbDumpContext(addr uintptr, maxAddr uintptr, label string) {
	start := addr
	bugbPuts("  context ")
	bugbPuts(label)
	bugbPuts(" [0x")
	bugbPutHex64(uint64(start))
	bugbPuts("-0x")
	bugbPutHex64(uint64(start + 32))
	bugbPuts("]:\n")

	// Print 4 rows of 8 bytes each = 32 bytes
	for row := uintptr(0); row < 4; row++ {
		bugbPuts("    ")
		rowStart := start + row*8
		bugbPutHex64(uint64(rowStart))
		bugbPuts(": ")
		// Hex
		for col := uintptr(0); col < 8; col++ {
			readAddr := rowStart + col
			if readAddr < maxAddr {
				b := *(*byte)(unsafe.Pointer(readAddr))
				hi := b >> 4
				lo := b & 0xF
				if hi < 10 {
					kmazarinUART('0' + hi)
				} else {
					kmazarinUART('a' - 10 + hi)
				}
				if lo < 10 {
					kmazarinUART('0' + lo)
				} else {
					kmazarinUART('a' - 10 + lo)
				}
			} else {
				bugbPuts("??")
			}
			kmazarinUART(' ')
		}
		// ASCII
		bugbPuts(" |")
		for col := uintptr(0); col < 8; col++ {
			readAddr := rowStart + col
			if readAddr < maxAddr {
				b := *(*byte)(unsafe.Pointer(readAddr))
				if b >= 32 && b < 127 {
					kmazarinUART(b)
				} else {
					kmazarinUART('.')
				}
			} else {
				kmazarinUART('*')
			}
		}
		bugbPuts("|\n")
	}
}

