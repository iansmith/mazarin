// throw triggers a fatal error that dumps a stack trace and exits.
//
// throw should be used for runtime-internal fatal errors where Go itself,
// rather than user code, may be at fault for the failure.
//
// throw should be an internal detail,
// but widely used packages access it using linkname.
// Notable members of the hall of shame include:
//   - github.com/bytedance/sonic
//   - github.com/cockroachdb/pebble
//   - github.com/dgraph-io/ristretto
//   - github.com/outcaste-io/ristretto
//   - github.com/pingcap/br
//   - gvisor.dev/gvisor
//   - github.com/sagernet/gvisor
//
// Do not remove or change the type signature.
// See go.dev/issue/67401.
//
//go:linkname throw
//go:nosplit
func throw(s string) {
	// Bug-B diagnostic: scan the current goroutine's stack for the
	// " failed " corruption pattern before fatalthrow unwinds.
	throwPreDiag(s)

	// Everything throw does should be recursively nosplit so it
	// can be called even when it's unsafe to grow the stack.
	systemstack(func() {
		print("fatal error: ")
		printindented(s) // logically printpanicval(s), but avoids convTstring write barrier
		print("\n")
	})

	fatalthrow(throwTypeRuntime)
}

// throwPreDiag captures goroutine state before throw() exits.
// Uses kmazarinUART directly (bypasses suppressSerial) to guarantee output
// is visible even when the soft IRQ console is active.
//
//go:nosplit
func throwPreDiag(s string) {
	bugbPuts("BUG-B: throw(\"")
	bugbPuts(s)
	bugbPuts("\")\n")

	gp := getg()
	if gp == nil {
		return
	}
	bugbPuts("  g=0x")
	bugbPutHex64(uint64(uintptr(unsafe.Pointer(gp))))
	bugbPuts(" stack=[0x")
	bugbPutHex64(uint64(gp.stack.lo))
	bugbPuts(",0x")
	bugbPutHex64(uint64(gp.stack.hi))
	bugbPuts("] guard=0x")
	bugbPutHex64(uint64(gp.stackguard0))
	bugbPuts("\n")

	// Scan the full goroutine stack for " failed " pattern.

	lo := uintptr(gp.stack.lo)
	hi := uintptr(gp.stack.hi)
	if hi <= lo || hi-lo > 1<<30 {
		return
	}
	found := uintptr(0)
	for addr := lo; addr < hi && found < 16; addr += 8 {
		v := *(*uint64)(unsafe.Pointer(addr))
		if v == 0x2064656C69616620 {
			if found == 0 {
				bugbPuts("  STACK SCAN: found ' failed ' at:\n")
			}
			bugbPuts("    offset 0x")
			bugbPutHex64(uint64(addr - lo))
			bugbPuts(" addr=0x")
			bugbPutHex64(uint64(addr))
			bugbPuts("\n")
			bugbDumpContext(addr, hi, "throwPreDiag")
			found++
		}
	}

	bugbPuts("  HEAP-METADATA-SCAN:\n")
	ScanHeapMetadataForFailed()
}

